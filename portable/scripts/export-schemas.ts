/**
 * Exports the contract-v3 Zod schemas as JSON Schema (draft 2020-12) documents into portable/schemas/v3/.
 *   tsx portable/scripts/export-schemas.ts
 * A test (schemas.test.ts) fails when the committed files are stale.
 */
import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { z } from "zod";
import { ManifestSchema, CONTRACT_VERSION } from "../src/contract/manifest.js";
import { RECORD_SCHEMAS, RECORD_TYPE_ORDER } from "../src/contract/records.js";

export const SCHEMA_DIR = path.join(path.dirname(fileURLToPath(import.meta.url)), "..", "schemas", "v3");
const BASE = "https://schemas.readypackets.example/portable/v3/";

export function buildSchemas(): Map<string, string> {
  const out = new Map<string, string>();
  const emit = (name: string, schema: z.ZodType, title: string) => {
    const doc = { $id: `${BASE}${name}`, title, ...z.toJSONSchema(schema, { target: "draft-2020-12", unrepresentable: "any", io: "input" }) };
    out.set(name, JSON.stringify(doc, null, 2) + "\n");
  };
  emit("manifest.schema.json", ManifestSchema, `ReadyPackets portable manifest (contract ${CONTRACT_VERSION})`);
  for (const type of RECORD_TYPE_ORDER) emit(`records/${type}.schema.json`, RECORD_SCHEMAS[type] as z.ZodType, `ReadyPackets portable record: ${type} (contract ${CONTRACT_VERSION})`);
  return out;
}

export const RECORDS_DOC = path.join(path.dirname(fileURLToPath(import.meta.url)), "..", "docs", "RECORDS.md");

interface JsonSchemaNode {
  type?: string | string[];
  anyOf?: JsonSchemaNode[];
  properties?: Record<string, JsonSchemaNode>;
  required?: string[];
  items?: JsonSchemaNode;
  pattern?: string;
  format?: string;
  enum?: unknown[];
  const?: unknown;
  maxLength?: number;
  $ref?: string;
}

function describeType(n: JsonSchemaNode): string {
  if (n.anyOf) return n.anyOf.map(describeType).join(" \\| ");
  if (n.$ref) return "JSON value";
  if (n.const !== undefined) return `\`${JSON.stringify(n.const)}\``;
  if (n.enum) return n.enum.map((v) => `\`${String(v)}\``).join(" / ");
  if (n.type === "array") return `array of ${n.items ? describeType(n.items) : "values"}`;
  if (n.type === "object") return n.properties && "amountMinor" in n.properties ? "money" : n.properties && "kind" in n.properties && "publicId" in n.properties ? "actor" : "object";
  if (n.type === "string") {
    if (n.pattern === "^[0-7][0-9A-HJKMNP-TV-Z]{25}$") return "ULID";
    if (n.pattern?.includes("Z$") || n.format === "date-time") return "UTC time";
    if (n.pattern === "^[a-f0-9]{64}$") return "sha256 hex";
    return n.maxLength ? `string ≤${n.maxLength}` : "string";
  }
  return Array.isArray(n.type) ? n.type.join(" \\| ") : (n.type ?? "any");
}

/** Generated field dictionary for every record type (kept current by golden.test.ts). */
export function buildRecordsDoc(): string {
  const lines = [
    "# Contract v3 record dictionary (generated)",
    "",
    "Generated by `portable/scripts/export-schemas.ts` from the normative Zod schemas in",
    "`portable/src/contract/records.ts`. Do not edit by hand. \"req\" = key must be present (it may still be",
    "nullable). Every record type also allows the optional `heldUnknown` object (inert source evidence).",
    "",
  ];
  for (const type of RECORD_TYPE_ORDER) {
    const doc = z.toJSONSchema(RECORD_SCHEMAS[type] as z.ZodType, { target: "draft-2020-12", unrepresentable: "any", io: "input" }) as JsonSchemaNode;
    lines.push(`## ${type}`, "", `File \`records/${type}.jsonl\` · schema \`schemas/v3/records/${type}.schema.json\``, "", "| field | req | type |", "| --- | --- | --- |");
    for (const [k, v] of Object.entries(doc.properties ?? {})) {
      if (k === "heldUnknown") continue;
      lines.push(`| \`${k}\` | ${doc.required?.includes(k) ? "yes" : "no"} | ${describeType(v)} |`);
    }
    lines.push("");
  }
  return lines.join("\n");
}

export async function writeSchemas(dir = SCHEMA_DIR): Promise<number> {
  const docs = buildSchemas();
  await mkdir(path.join(dir, "records"), { recursive: true });
  for (const [name, text] of docs) await writeFile(path.join(dir, name), text);
  await writeFile(RECORDS_DOC, buildRecordsDoc());
  return docs.size;
}

const isMain = process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href;
if (isMain) {
  writeSchemas().then(
    (n) => process.stdout.write(`wrote ${n} schema documents to ${SCHEMA_DIR}\n`),
    (e: unknown) => {
      process.stderr.write(`schema export failed: ${e instanceof Error ? e.message : "unknown error"}\n`);
      process.exitCode = 1;
    },
  );
}
