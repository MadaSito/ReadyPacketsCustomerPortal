import type { AuditCategory, Severity } from "../../core/types.js";

/**
 * Authoritative SIEM forwarding catalogue for ReadyPackets audit events.
 *
 * Owner: siem_engineer.
 *
 * External projection rules enforced by `projection.ts`:
 *  1. Local correlation tokens (`address_ref`, `account_ref`, `source_address_ref`, `session_ref`)
 *     and installation-local numeric/public identifiers (`actor_user_id`, `subject_user_id`,
 *     `*_public_id`) are NEVER forwarded in `attributes`; external correlation uses the envelope's
 *     keyed `actor_ref`, `resource_ref`, and `correlation_id`.
 *  2. Free-form operator/customer text (`reason`, `note`, `warning_text`, `label`, `source_label`),
 *     raw network addresses/CIDRs, e-mails, and monetary figures are NEVER forwarded.
 *  3. SIEM's own operational delivery/spool/cursor diagnostics (`forwardable: false`) are never
 *     re-spooled into outbound destinations.
 */
export interface SiemCatalogueEntry {
  /** Exact `event_name` or trailing `.*` namespace prefix. */
  readonly eventName: string;
  readonly category: AuditCategory;
  readonly defaultSeverity: Severity;
  readonly resourceType: string | null;
  readonly description: string;
  /** Allowlisted `attributes` keys permitted to leave the installation for this event. */
  readonly forwardedAttributes: readonly string[];
  /** Allowlisted `safe_counts` metric keys permitted to leave the installation for this event. */
  readonly forwardedSafeCounts: readonly string[];
  /** Local-only or sensitive keys explicitly stripped before external transmission. */
  readonly withheldLocalKeys: readonly string[];
  /** True when eligible for outbound SIEM delivery when destination category + minSeverity match. */
  readonly forwardable: boolean;
  readonly increment: "baseline" | "05" | "06" | "07";
}

