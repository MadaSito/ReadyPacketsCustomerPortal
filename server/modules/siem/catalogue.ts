/**
 * Resolves the authoritative SIEM catalogue entry for an `event_name` (exact match first,
 * then longest `.*` prefix pattern).
 */
export function findSiemCatalogueEntry(eventName: string): SiemCatalogueEntry | null {
  for (const entry of SIEM_EVENT_CATALOGUE) {
    if (entry.eventName === eventName) {
      return entry;
    }
  }
  let bestMatch: SiemCatalogueEntry | null = null;
  for (const entry of SIEM_EVENT_CATALOGUE) {
    if (!entry.eventName.endsWith(".*")) continue;
    const prefix = entry.eventName.slice(0, -1); // retains trailing dot
    if (eventName.startsWith(prefix)) {
      if (!bestMatch || entry.eventName.length > bestMatch.eventName.length) {
        bestMatch = entry;
      }
    }
  }
  return bestMatch;
}
